def context(text, source='B', status='context'):
    prefixes = {'context': 'ИЗ ПРОЕКТА', 'claim': 'ПУБЛИЧНОЕ ЗАЯВЛЕНИЕ', 'notes': 'РАБОЧИЕ ЗАМЕТКИ'}
    node = n(f'{prefixes[status]} [{source}] · {text}')
    node['status'] = status
    return node

